"""Build results/leaderboard.{md,csv} from every runs/*/<task>.json.

Numbers come only from the runner's `statistics` block; nothing is typed by hand.
Rows are grouped by task; budget is printed so runs with different budgets are never
silently compared.

Usage: python tools/report.py
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
OUT = ROOT / "results"
TASK_ORDER = ["causal_n4", "3d", "boolean_basic", "boolean_extended", "boolean_full"]
COLS = ["task", "run", "model", "tag", "budget", "n", "parse", "VR", "NR", "RR", "tokens_per_sample", "commit"]


def budget(res, meta_task):
    if res.get("n_queries_per_sample"):
        return f"fixed={res['n_queries_per_sample']}"
    m = res.get("query_multiplier") or (meta_task or {}).get("multiplier")
    return f"x{m:g}" if m is not None else "?"


def parse_rate(res):
    rates = [r["parse_success_rate"] for r in res["per_sample_results"] if "parse_success_rate" in r]
    return sum(rates) / len(rates) if rates else None


def rows():
    for run in sorted(p for p in RUNS.iterdir() if p.is_dir()):
        meta_path = run / "meta.json"
        meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
        if meta.get("suite") == "smoke":  # pipeline checks, never reportable
            continue
        for f in sorted(run.glob("*.json")):
            if f.name == "meta.json":
                continue
            res = json.loads(f.read_text())
            if "statistics" not in res:
                continue
            s = res["statistics"]
            yield {
                "task": f.stem,
                "run": run.name,
                "model": meta.get("served_model") or res.get("llm_name", "?"),
                "tag": meta.get("tag") or "",
                "budget": budget(res, meta.get("tasks", {}).get(f.stem)),
                "n": len(res["per_sample_results"]),
                "parse": parse_rate(res),
                "VR": s["valid_rate"]["mean"],
                "NR": s["novelty_rate"]["mean"],
                "RR": s["recovery_rate"]["mean"],
                "tokens_per_sample": round(res["token_usage"]["avg_tokens_per_sample"]),
                "commit": ((meta.get("git") or {}).get("commit") or "")[:8],
            }


def fmt(v):
    if v is None:
        return "-"
    return f"{100 * v:.1f}" if isinstance(v, float) else str(v)


def main():
    data = list(rows())
    data.sort(key=lambda r: (TASK_ORDER.index(r["task"]) if r["task"] in TASK_ORDER else 99, r["task"], -r["RR"]))
    OUT.mkdir(exist_ok=True)

    with open(OUT / "leaderboard.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        w.writerows(data)

    lines = [
        "# Leaderboard",
        "",
        "Generated by `make report` from `runs/*/`. VR/NR/RR/parse in %. Sorted by RR within each task.",
        "Only compare rows with the same budget.",
        "",
    ]
    for task in dict.fromkeys(r["task"] for r in data):
        lines += [f"## {task}", "", "| " + " | ".join(COLS[1:]) + " |", "|" + "---|" * (len(COLS) - 1)]
        lines += ["| " + " | ".join(fmt(r[c]) for c in COLS[1:]) + " |" for r in data if r["task"] == task]
        lines.append("")
    (OUT / "leaderboard.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
